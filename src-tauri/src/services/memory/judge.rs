//! LLM arbitration: when a new fact is highly similar to or conflicts with an existing one, decide merge / update / supersede / keep_separate.
//!
//! Arbitration only triggers on high vector-neighbor scores (e.g. >= 0.92), and every failure fails safe to keep_separate (prefer redundancy over wrong merges or deletions).

use crate::services::memory::llm::{chat_json, LlmConfig};
use serde::{Deserialize, Serialize};

/// Arbitration action.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
#[serde(rename_all = "snake_case")]
pub enum JudgeAction {
    /// The two facts are different; keep both (default / fallback)
    KeepSeparate,
    /// The new fact is more accurate; correct the existing fact with it
    Update,
    /// Merge into a single fact (content generated by the model)
    Merge,
    /// The new fact supersedes the existing one (conflict / outdated)
    Supersede,
}

/// Arbitration JSON returned by the model.
#[derive(Deserialize)]
struct JudgeResponse {
    #[serde(default = "default_action")]
    action: String,
    #[serde(default)]
    merged_content: String,
    #[serde(default, rename = "reason")]
    _reason: String,
}

fn default_action() -> String {
    "keep_separate".into()
}

/// Arbitrate: given an existing fact and a new fact, return the action (and the merged content).
pub async fn judge(cfg: &LlmConfig, existing: &str, incoming: &str) -> (JudgeAction, String) {
    let system = concat!(
        "你是项目记忆库的仲裁器。两个事实来自同一项目，语义高度相似。判定二者关系：\n",
        "- merge：可无损合并为一条更完整的表述（输出 merged_content）；\n",
        "- update：新事实更准确/更新，以新事实为准（旧内容作废）；\n",
        "- supersede：新事实明确取代旧事实（如依赖迁移、方案变更，旧内容过时）；\n",
        "- keep_separate：二者是不同的事实，即便有重叠。\n",
        "只输出 JSON：{action: merge|update|supersede|keep_separate, merged_content: 字符串, reason: 一句话}。",
    );
    let user = format!("既有事实：\n{existing}\n\n新事实：\n{incoming}");
    match chat_json(cfg, system, &user, 300).await {
        Ok(v) => parse_response(&v),
        Err(_) => (JudgeAction::KeepSeparate, String::new()),
    }
}

/// Record the arbitration action into the 7-day rolling stats (self-evolution quality probe: the action distribution is measurable).
pub fn bump_judge_stat(store: &crate::services::memory::store::MemoryStore, action: &JudgeAction) {
    let key = match action {
        JudgeAction::Merge => crate::services::memory::store::STAT_JUDGE_MERGE,
        JudgeAction::Update => crate::services::memory::store::STAT_JUDGE_UPDATE,
        JudgeAction::Supersede => crate::services::memory::store::STAT_JUDGE_SUPERSEDE,
        JudgeAction::KeepSeparate => crate::services::memory::store::STAT_JUDGE_KEEP,
    };
    store.rolling_bump(key, 1);
}

/// Parse the arbitration response (fault-tolerant: any anomaly falls back to keep_separate).
pub fn parse_response(v: &serde_json::Value) -> (JudgeAction, String) {
    let fallback = JudgeResponse {
        action: "keep_separate".into(),
        merged_content: String::new(),
        _reason: String::new(),
    };
    let resp = serde_json::from_value::<JudgeResponse>(v.clone()).unwrap_or(fallback);
    let action = match resp.action.as_str() {
        "update" => JudgeAction::Update,
        "merge" => JudgeAction::Merge,
        "supersede" => JudgeAction::Supersede,
        _ => JudgeAction::KeepSeparate,
    };
    (action, resp.merged_content)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn test_parse_actions() {
        assert_eq!(
            parse_response(&json!({ "action": "merge", "merged_content": "A+B", "reason": "r" })).0,
            JudgeAction::Merge,
        );
        assert_eq!(
            parse_response(&json!({ "action": "update" })).0,
            JudgeAction::Update
        );
        assert_eq!(
            parse_response(&json!({ "action": "supersede" })).0,
            JudgeAction::Supersede,
        );
        assert_eq!(
            parse_response(&json!({ "action": "garbage" })).0,
            JudgeAction::KeepSeparate,
        );
        assert_eq!(parse_response(&json!([])).0, JudgeAction::KeepSeparate);
    }

    #[test]
    fn test_merged_content() {
        let (action, content) =
            parse_response(&json!({ "action": "merge", "merged_content": "整合后的内容" }));
        assert_eq!(action, JudgeAction::Merge);
        assert_eq!(content, "整合后的内容");
    }
}
